package domain

import "time"

// AuditLogTTL — сколько держим журнал действий. Год: страница журнала
// показывает только последние записи, а глубже смотрят, когда разбирают
// историю конкретной карточки или доступа, — и год назад это ещё бывает
// нужно, а дальше уже нет.
//
// Как и журнал входов, из интерфейса он не чистится: записи убирает
// только уборщик по сроку.
const AuditLogTTL = 365 * 24 * time.Hour
