package domain

import "time"

// CheckedGame — партия, которую пользователь смотрел: что за партия и когда
// он открывал её в последний раз.
type CheckedGame struct {
	GameID string
	// Title — название на момент последней проверки. Пустое бывает у партии,
	// про которую сайт игры промолчал.
	Title     string
	CheckedAt time.Time
}

// CheckedGamesTTL — сколько партия держится в списке проверенных без новых
// заходов. Список нужен, чтобы возвращаться к тому, чем занят сейчас,
// а не вести журнал: партия, к которой не приходили неделю, уходит сама,
// и чистить список руками не приходится.
const CheckedGamesTTL = 7 * 24 * time.Hour
