package domain

import "time"

// MaxCommentLen — предел комментария к врагу. Тот же, что у заметки: пишут
// их одними и теми же словами.
const MaxCommentLen = 4000

// Enemy — запись личного списка врагов: чужая карточка и комментарий «за что».
// Список личный, поэтому одна карточка бывает врагом у нескольких человек,
// у каждого со своим комментарием.
//
// На шкалы риска и лояльности запись не влияет — как и статус клана: шкалы
// про репутацию игрока, а список врагов — личное дело того, кто его ведёт.
type Enemy struct {
	Player    *Player
	Comment   string
	CreatedAt time.Time
}
