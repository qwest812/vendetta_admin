package domain

import (
	"fmt"
	"net"
	"net/netip"
	"time"
)

// LoginLogTTL — сколько держим записи о входах. Полгода: журнал нужен,
// чтобы разобраться в спорном случае, а спор всплывает спустя недели.
//
// Из интерфейса записи не удаляются вовсе — их убирает только уборщик
// по сроку. Кнопка «очистить» сделала бы журнал бесполезным: первым делом
// почистили бы ровно то, из-за чего к нему пришли.
const LoginLogTTL = 180 * 24 * time.Hour

// SharedLoginWindow — за какой срок считаем подсети, из которых входили
// в аккаунт. Месяц: за неделю человек может и не выйти из дома, а за год
// сменит и провайдера, и город, и это уже не про раздачу доступа.
const SharedLoginWindow = 30 * 24 * time.Hour

// SharedLoginSubnets — с какого числа подсетей аккаунт попадает в сводку
// общих входов. Три, а не два: телефон и домашний вайфай — это уже две
// подсети у любого честного человека.
//
// Метка ничего не доказывает и доказывать не должна. Три подсети за месяц
// одинаково хорошо объясняются и раздачей пароля, и поездкой; она говорит
// «посмотрите на этот аккаунт», а не «этот аккаунт общий».
const SharedLoginSubnets = 3

// Маски, до которых сворачивается адрес. /24 у IPv4 — обычный размер
// куска, который провайдер держит на одном узле; /48 у IPv6 — то, что
// выдают одному абоненту целиком.
//
// Точный адрес для этого не годится: мобильный интернет меняет его
// по нескольку раз в день, и разными оказались бы все входы подряд —
// помечены были бы все, и метка не значила бы ничего.
const (
	subnetBitsV4 = 24
	subnetBitsV6 = 48
)

// LoginPlace — откуда пришёл вход: сам адрес и подсеть, до которой он
// свёрнут. Пустое значение означает «адрес не разобрали».
type LoginPlace struct {
	IP     string // «203.0.113.9»
	Subnet string // «203.0.113.0/24»
}

// ParseLoginPlace разбирает адрес, каким его видит сервер: «ip:порт»
// из http.Request.RemoteAddr либо просто адрес.
//
// Заголовки прокси здесь не читаются намеренно. Админка открыта портом
// наружу, и доверять X-Forwarded-For значило бы разрешить любому подписать
// свой вход чужим адресом — журнал стал бы врать. Появится прокси, появится
// и разбор заголовка, но вместе с настройкой доверенных адресов.
func ParseLoginPlace(remoteAddr string) (LoginPlace, error) {
	host := remoteAddr
	// RemoteAddr у tcp-слушателя всегда «адрес:порт», но эта же функция
	// разбирает и то, что набрали в фильтре журнала, — там порта нет.
	if h, _, err := net.SplitHostPort(remoteAddr); err == nil {
		host = h
	}
	addr, err := netip.ParseAddr(host)
	if err != nil {
		return LoginPlace{}, fmt.Errorf("адрес %q не разобран: %w", remoteAddr, err)
	}
	// Зона IPv6 («fe80::1%eth0») в базу не поедет: тип inet её не примет,
	// а к месту она ничего не добавляет. Unmap разворачивает «::ffff:1.2.3.4»
	// обратно в IPv4 — это тот же адрес, и сворачивать его надо по-ipv4.
	addr = addr.WithZone("").Unmap()

	bits := subnetBitsV6
	if addr.Is4() {
		bits = subnetBitsV4
	}
	subnet, err := addr.Prefix(bits)
	if err != nil {
		return LoginPlace{}, fmt.Errorf("подсеть адреса %q: %w", host, err)
	}
	return LoginPlace{IP: addr.String(), Subnet: subnet.String()}, nil
}
