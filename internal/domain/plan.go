package domain

// Plan — пакет доступа: сколько человеку открыто в админке.
//
// Это не роль и не её продолжение. Role отвечает на вопрос «кем он вправе
// управлять»: кто правит чужие карточки, кто раздаёт доступы. Пакет отвечает
// на другой — «сколько ему самому можно». Поэтому админ с базовым пакетом
// правит чужие карточки, а свой личный список ведёт по базовым правилам,
// и никакого противоречия тут нет.
//
// Пакеты вложены друг в друга: каждый следующий — это всё, что было
// в предыдущем, плюс новое. Отсюда и вес, как у ролей: вопрос «не ниже ли
// расширенного» должен отвечаться одним AtLeast, а не перечислением.
type Plan string

const (
	PlanBasic    Plan = "basic"
	PlanExtended Plan = "extended"
	PlanUltra    Plan = "ultra"
)

var planWeight = map[Plan]int{PlanBasic: 1, PlanExtended: 2, PlanUltra: 3}

// Plans — все пакеты по возрастанию: в таком порядке их и показывают в выборе.
var Plans = []Plan{PlanBasic, PlanExtended, PlanUltra}

func (p Plan) Valid() bool { _, ok := planWeight[p]; return ok }

// AtLeast сообщает, что пакет не ниже требуемого.
func (p Plan) AtLeast(min Plan) bool { return planWeight[p] >= planWeight[min] }

// TitleKey — ключ подписи к пакету, как у роли. Незнакомый пакет подписываем
// его же кодом: колонка в базе с проверкой и таких не хранит, но выдумывать
// ему название хуже, чем показать как есть.
func (p Plan) TitleKey() string {
	if _, ok := planWeight[p]; ok {
		return "plan." + string(p)
	}
	return string(p)
}

// relationLimits — сколько карточек пакет разрешает держать в личных списках.
// Счёт общий на оба: враги и друзья — один запас на человека, и делить его
// между списками он волен сам.
//
// Ноль означает «без предела», а не «ничего нельзя»: запрет личных списков
// не предусмотрен ни одним пакетом, а вот безлимит — предусмотрен.
//
// Здесь же будет и то, что откроют следующие пакеты. Таблица «что открыто»
// должна остаться одной: стоит начать спрашивать название пакета
// в обработчиках, и через две итерации таких мест будет двадцать.
var relationLimits = map[Plan]int{
	PlanBasic:    20,
	PlanExtended: 50,
	PlanUltra:    0,
}

// RelationLimit — предел личных списков. Незнакомый пакет считаем базовым:
// ошибиться в меньшую сторону безопаснее, чем открыть лишнее.
func (p Plan) RelationLimit() int {
	if n, ok := relationLimits[p]; ok {
		return n
	}
	return relationLimits[PlanBasic]
}

// CanSeeLastSeen — показывать ли в карточке, когда игрока встречали в партии
// и в какой именно. Это след наших собственных заходов в игру, а не общая
// справка: по нему видно, за кем и когда мы ходили смотреть.
//
// Пакеты вложены друг в друга, поэтому спрашиваем AtLeast, а не равенство:
// у ультра это тоже открыто, и дописывать его сюда не придётся.
func (p Plan) CanSeeLastSeen() bool { return p.AtLeast(PlanExtended) }

// CanSeeAnonymousMaps — пускать ли на карту партии, объявленной анонимной.
// В такой партии игра прячет имена всех участников, а мы их всё равно
// называем: имя скрыто, а номер аккаунта в состоянии настоящий, и состав
// с сайта по нему называет живого человека. Снятая анонимность — самое
// острое, что админка умеет, и открыта она только ультра-пакету.
func (p Plan) CanSeeAnonymousMaps() bool { return p.AtLeast(PlanUltra) }
