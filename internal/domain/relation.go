package domain

import "time"

// MaxCommentLen — предел комментария к записи личного списка. Тот же, что
// у заметки: пишут их одними и теми же словами.
const MaxCommentLen = 4000

// Relation — запись личного списка: чужая карточка и комментарий «за что»
// или «чем хорош». Списков два — враги и друзья, — и устроены они одинаково,
// поэтому запись у них общая.
//
// Списки личные, поэтому одна карточка бывает у разных людей в разных
// списках: кому-то этот игрок друг, кому-то враг.
//
// На шкалы риска и лояльности запись не влияет — как и статус клана: шкалы
// про репутацию игрока, а личный список — дело того, кто его ведёт.
type Relation struct {
	Player    *Player
	Comment   string
	CreatedAt time.Time
}
