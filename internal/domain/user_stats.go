package domain

import "time"

// UserStats — боевой счёт игрока по данным сайта игры. Считается по всем
// партиям аккаунта сразу, поэтому принадлежит человеку, а не партии.
//
// Defeated и Casualties — только бои с живыми игроками: бои с компьютерными
// сайт держит отдельным набором, и складывать их не стоит. Ботов фармят,
// и опасности в партии это не прибавляет.
//
// CheckedAt пусто у того, кто стоит в очереди, но ещё не спрошен. Отличать
// это от нулей обязательно: ноль у спрошенного значит «не воевал», у
// неспрошенного — «не знаем».
type UserStats struct {
	SiteUserID    string
	Level         int
	Defeated      int64
	Casualties    int64
	Games         int
	SoloWins      int
	CoalitionWins int
	OverallScore  int64
	CheckedAt     *time.Time
}

// Known — спрашивали ли про игрока вообще.
func (s UserStats) Known() bool { return s.CheckedAt != nil }

// Rated — есть ли чем мерить. Уровень бывает нулевым и у спрошенного:
// так отвечает сайт про удалённые аккаунты, и красить такого не по чему.
func (s UserStats) Rated() bool { return s.Level > 0 }

// KD — сколько чужих войск игрок сносит на каждое своё потерянное.
// Знаменатель не меньше единицы: так же считает и сам клиент игры, а иначе
// делить на ноль пришлось бы у каждого, кто ещё не терял войск.
func (s UserStats) KD() float64 {
	if s.Casualties < 1 {
		return float64(s.Defeated)
	}
	return float64(s.Defeated) / float64(s.Casualties)
}

// Danger — насколько игрок опасен: уровень, умноженный на кд. Уровень один
// говорит только о наигранном времени, кд одно — об умении в бою; опасен
// тот, у кого сошлось и то и другое. Двадцатый уровень с кд 1.0 (20.0)
// выходит спокойнее семнадцатого с кд 1.2 (20.4) — и это верно по сути.
func (s UserStats) Danger() float64 { return float64(s.Level) * s.KD() }
