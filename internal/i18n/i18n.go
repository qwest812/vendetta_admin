// Package i18n — язык интерфейса. Языков два, и оба лежат рядом в одном
// словаре: перевод, вынесенный в отдельный файл, расходится с оригиналом
// молча, а здесь расхождение видно глазами и ловится тестом.
//
// Ключ сообщения — это его смысл, а не текст: «nav.search», а не «Поиск».
// Тогда правка русской формулировки не тащит за собой правку английской
// и не ломает шаблоны.
package i18n

import (
	"fmt"
	"sort"
)

type Lang string

const (
	RU Lang = "ru"
	EN Lang = "en"
)

// Default — язык, на котором админка говорит, пока её об этом не просили.
// Команда русскоязычная, и по-русски написан весь исходный текст.
const Default = RU

// All — все языки в том порядке, в каком их показывать в переключателе.
var All = []Lang{RU, EN}

// Parse приводит к языку то, что пришло из куки или адреса. Незнакомое —
// не ошибка, а чаще всего протухшая кука: отвечать на неё пятисоткой
// незачем, честнее молча вернуться к языку по умолчанию.
func Parse(s string) Lang {
	for _, l := range All {
		if string(l) == s {
			return l
		}
	}
	return Default
}

// Valid — знаем ли мы такой язык. Нужно там, где неизвестный язык означает
// ошибку в адресе, а не повод подставить умолчание.
func Valid(s string) bool {
	for _, l := range All {
		if string(l) == s {
			return true
		}
	}
	return false
}

// Title — как язык называет сам себя. В переключателе нужно именно это:
// «English» ищут глазами те, кто русского не читает, и переводить название
// на текущий язык значило бы прятать его от них.
func (l Lang) Title() string {
	if l == EN {
		return "English"
	}
	return "Русский"
}

// Short — подпись на самой кнопке переключателя.
func (l Lang) Short() string {
	if l == EN {
		return "EN"
	}
	return "RU"
}

// T — сообщение по ключу, при необходимости со вставками (как у Sprintf).
//
// Ключ, которого в словаре нет, возвращается как есть: на странице такое
// видно сразу, а падать из-за подписи к кнопке админка не должна. Что все
// ключи из шаблонов в словаре есть, проверяет тест.
func (l Lang) T(id string, args ...any) string {
	m, ok := messages[id]
	if !ok {
		return id
	}
	s := m.ru
	// Пустой перевод означает «ещё не переведено», а не «пустая строка»:
	// показать русский честнее, чем пустоту на месте подписи.
	if l == EN && m.en != "" {
		s = m.en
	}
	if len(args) > 0 {
		return fmt.Sprintf(s, args...)
	}
	return s
}

// Has — есть ли такой ключ в словаре. Нужно тесту, который сверяет
// словарь с шаблонами: опечатка в ключе иначе всплывёт только на странице.
func Has(id string) bool {
	_, ok := messages[id]
	return ok
}

// Untranslated — ключи, у которых нет английского. Пустой перевод работает
// (покажется русский), но это долг, и тест о нём напоминает.
func Untranslated() []string {
	var out []string
	for id, m := range messages {
		if m.en == "" {
			out = append(out, id)
		}
	}
	sort.Strings(out)
	return out
}

// Keys — все ключи словаря. По ним тест находит те, что уже никем
// не используются: мёртвый перевод хуже отсутствующего, его правят зря.
func Keys() []string {
	out := make([]string, 0, len(messages))
	for id := range messages {
		out = append(out, id)
	}
	sort.Strings(out)
	return out
}
