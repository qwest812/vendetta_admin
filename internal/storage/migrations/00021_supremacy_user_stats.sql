-- +goose Up
-- Боевой счёт игрока по данным сайта игры: уровень, сколько чужих войск
-- снёс и сколько своих потерял. Считает это сайт по всем партиям аккаунта,
-- поэтому здесь свойство человека, а не партии, — как и бан.
--
-- Таблица — только кеш, без очереди: счёт пересчитывает сама страница
-- партии, когда видит игрока с устаревшей записью. Сайт отвечает про
-- одного игрока за раз, и спрашивать всю базу подряд незачем — нужны
-- ровно те, кто на открытой карте.
CREATE TABLE supremacy_user_stats (
    site_user_id   TEXT PRIMARY KEY,
    -- Уровень игрока. Ноль означает «сайт ничего не сказал»: у настоящего
    -- игрока уровень всегда хотя бы первый.
    level          INT NOT NULL DEFAULT 0,
    -- Бои с живыми игроками. Бои с компьютерными сайт держит отдельно,
    -- и мешать их не стоит: ботов фармят, а не воюют с ними.
    defeated       BIGINT NOT NULL DEFAULT 0,
    casualties     BIGINT NOT NULL DEFAULT 0,
    -- Остальное — для подсказки на карте: сколько партий сыграно и чем
    -- кончились.
    games          INT NOT NULL DEFAULT 0,
    solo_wins      INT NOT NULL DEFAULT 0,
    coalition_wins INT NOT NULL DEFAULT 0,
    overall_score  BIGINT NOT NULL DEFAULT 0,
    -- Когда считали. По нему страница и решает, пора ли спрашивать заново.
    checked_at     TIMESTAMPTZ NOT NULL
);

