-- Игровой ID теперь ключ регистрации: по нему находится уже заведённый
-- аккаунт, и из игры по нему берётся ник. Двум людям с одним ID места нет —
-- иначе регистрация не знала бы, к кому из них дописывать почту.
--
-- Пустая строка означает «не указан», и таких сколько угодно. Дубли среди
-- указанных миграция не разводит сама: кто из двоих назвал чужой ID, решает
-- рут, а не порядок строк. Если индекс не встал — найти их так:
--   SELECT game_id, array_agg(id) FROM users WHERE game_id <> ''
--    GROUP BY game_id HAVING count(*) > 1;
CREATE UNIQUE INDEX users_game_id_key ON users (game_id) WHERE game_id <> '';

